);

CREATE TABLE "clone_lab"."vector_store" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "owner_id" bigint NOT NULL,
  "source_session_record_id" bigint UNIQUE NOT NULL,
  "content" text NOT NULL,
  "embedding" vector(1536) NOT NULL,
  "metadata" jsonb NOT NULL DEFAULT '{}',
  "conversation_type" clone_lab.conversation_type NOT NULL DEFAULT 'owner',
  "kind" clone_lab.memory_kind,
  "created_at" timestamptz NOT NULL DEFAULT (clock_timestamp()),
  CONSTRAINT "long_term_owner_only" CHECK (conversation_type = 'owner')
);

