-- 명시적 실험 스키마 교체. 기존 clone_lab 데이터·객체는 보존하지 않는다.
BEGIN;
DROP SCHEMA IF EXISTS clone_lab CASCADE;
-- DBML 기준 14개 테이블. 기존 스키마 교체는 명시적 migration만 수행한다.
CREATE EXTENSION IF NOT EXISTS vector;
CREATE SCHEMA "clone_lab";

CREATE TYPE "clone_lab"."conversation_type" AS ENUM (
  'owner',
  'viewer'
);

CREATE TYPE "clone_lab"."message_status" AS ENUM (
  'pending',
  'analyzed',
  'saved',
  'archived'
);

CREATE TYPE "clone_lab"."run_status" AS ENUM (
  'running',
  'stopping',
  'paused',
  'failed',
  'completed',
  'cancelled'
);

CREATE TYPE "clone_lab"."memory_kind" AS ENUM (
  'FACT',
  'EXPERIENCE',
  'PREFERENCE',
  'CONDITIONAL_PREFERENCE',
  'VALUE',
  'HABIT',
  'GOAL',
  'RELATIONSHIP'
);

CREATE TABLE "clone_lab"."users" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" text NOT NULL,
  "persona" jsonb,
  "profile_version" bigint NOT NULL DEFAULT 0,
  "created_at" timestamptz NOT NULL DEFAULT (now())
);

CREATE TABLE "clone_lab"."sessions" (
  "session_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "memory_key" varchar(36) GENERATED ALWAYS AS (session_id::varchar(36)) STORED UNIQUE NOT NULL,
  "owner_id" bigint NOT NULL,
  "viewer_id" bigint NOT NULL,
  "conversation_type" clone_lab.conversation_type NOT NULL,
  "topic" text NOT NULL DEFAULT '',
  "analysis" jsonb NOT NULL DEFAULT '{}',
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  CONSTRAINT "owner_session_viewer_matches" CHECK (conversation_type <> 'owner' OR owner_id = viewer_id)
);

CREATE TABLE "clone_lab"."runs" (
  "run_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "clone_owner_id" bigint NOT NULL,
  "session_id" bigint UNIQUE NOT NULL,
  "mode" text NOT NULL DEFAULT 'single-session-pipeline-v1',
  "topic" text NOT NULL,
  "status" clone_lab.run_status NOT NULL DEFAULT 'paused',
  "error" text,
  "target_pairs" int NOT NULL DEFAULT 1000,
  "generated_pairs" int NOT NULL DEFAULT 0,
  "analyzed_pairs" int NOT NULL DEFAULT 0,
  "saved_pairs" int NOT NULL DEFAULT 0,
  "input_tokens" bigint NOT NULL DEFAULT 0,
  "output_tokens" bigint NOT NULL DEFAULT 0,
  "cached_tokens" bigint NOT NULL DEFAULT 0,
  "llm_elapsed_ms" bigint NOT NULL DEFAULT 0,
  "wall_elapsed_ms" bigint NOT NULL DEFAULT 0,
  "retry_count" int NOT NULL DEFAULT 0,
  "config" jsonb NOT NULL DEFAULT ('{}'::jsonb),
  "state" jsonb NOT NULL DEFAULT ('{}'::jsonb),
  "result" jsonb NOT NULL DEFAULT ('{}'::jsonb),
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  "active_since" timestamptz,
  "heartbeat_at" timestamptz,
  "finished_at" timestamptz,
  CONSTRAINT "runs_target_full_segments" CHECK (target_pairs > 0 AND target_pairs % 10 = 0),
  CONSTRAINT "runs_progress_order" CHECK (0 <= saved_pairs AND saved_pairs <= analyzed_pairs AND analyzed_pairs <= generated_pairs AND generated_pairs <= target_pairs),
  CONSTRAINT "runs_completed_target" CHECK (status <> 'completed' OR saved_pairs = target_pairs),
  CONSTRAINT "runs_active_clock" CHECK ((status IN ('running','stopping')) = (active_since IS NOT NULL)),
  CONSTRAINT "runs_finished_clock" CHECK ((status IN ('completed','cancelled')) = (finished_at IS NOT NULL)),
  CONSTRAINT "runs_token_counts" CHECK (input_tokens >= 0 AND output_tokens >= 0 AND cached_tokens >= 0 AND cached_tokens <= input_tokens),
  CONSTRAINT "runs_usage_nonnegative" CHECK (llm_elapsed_ms >= 0 AND wall_elapsed_ms >= 0 AND retry_count >= 0),
  CONSTRAINT "runs_json_objects" CHECK (jsonb_typeof(config) = 'object' AND jsonb_typeof(state) = 'object' AND jsonb_typeof(result) = 'object')
);

CREATE TABLE "clone_lab"."session_messages" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "session_id" bigint NOT NULL,
  "content" text NOT NULL,
  "embedding" vector(1536),
  "metadata" jsonb NOT NULL DEFAULT '{}',
  "user_text" text NOT NULL,
  "assistant_text" text NOT NULL,
  "user_received_at" timestamptz NOT NULL,
  "assistant_received_at" timestamptz NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT (clock_timestamp()),
  "sequence_no" BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
  "pair_no" bigint NOT NULL,
  "status" clone_lab.message_status NOT NULL DEFAULT 'pending',
  CONSTRAINT "message_pair_positive" CHECK (pair_no > 0)
);

CREATE TABLE "clone_lab"."context" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "conversation_id" varchar(36) NOT NULL,
  "source_message_id" bigint REFERENCES clone_lab.session_messages(id),
  "is_active" boolean NOT NULL DEFAULT true,
  UNIQUE (source_message_id,type),
  "content" text NOT NULL,
  "type" varchar(10) NOT NULL,
  "timestamp" timestamp NOT NULL,
  CONSTRAINT "context_message_type_allowed" CHECK (type IN ('USER','ASSISTANT','SYSTEM','TOOL'))
);

CREATE TABLE "clone_lab"."context_summaries" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "session_id" bigint NOT NULL,
  "segment_no" int NOT NULL,
  "start_message_id" bigint NOT NULL,
  "end_message_id" bigint NOT NULL,
  "content" text NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT (clock_timestamp()),
